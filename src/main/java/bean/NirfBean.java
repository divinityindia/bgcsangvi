package bean;

public class NirfBean
{
  private int nmid;
  private String nmtitle;
  private int nrid;
  private String nrtitle;
  private String document;
public int getNmid() {
	return nmid;
}
public void setNmid(int nmid) {
	this.nmid = nmid;
}
public String getNmtitle() {
	return nmtitle;
}
public void setNmtitle(String nmtitle) {
	this.nmtitle = nmtitle;
}
public int getNrid() {
	return nrid;
}
public void setNrid(int nrid) {
	this.nrid = nrid;
}
public String getNrtitle() {
	return nrtitle;
}
public void setNrtitle(String nrtitle) {
	this.nrtitle = nrtitle;
}
public String getDocument() {
	return document;
}
public void setDocument(String document) {
	this.document = document;
}
  
  
}
